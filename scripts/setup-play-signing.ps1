# Creates release keystore + local gradle signing + optional GitHub Actions secrets.
# Requires: JDK (keytool), git credential for github.com with repo scope.
param(
    [switch]$PushGitHubSecrets
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot -Parent
$Cache = Join-Path $Root '.build-cache'
New-Item -ItemType Directory -Force -Path $Cache | Out-Null

$Jks = Join-Path $Cache 'sumrax-release.jks'
$Info = Join-Path $Cache 'play-signing.local.txt'

$alias = 'sumrax'
$storePass = 'SumrakPlay2026!'
$keyPass = $storePass

if (-not (Test-Path $Jks)) {
    $keytoolCmd = Get-Command keytool -ErrorAction SilentlyContinue
    $keytool = if ($keytoolCmd) { $keytoolCmd.Source } else { $null }
    if (-not $keytool) {
        $javaHome = $env:JAVA_HOME
        if ($javaHome) { $keytool = Join-Path $javaHome 'bin\keytool.exe' }
    }
    if (-not $keytool) {
        $studioKeytool = 'C:\Program Files\Android\Android Studio\jbr\bin\keytool.exe'
        if (Test-Path $studioKeytool) { $keytool = $studioKeytool }
    }
    if (-not $keytool -or -not (Test-Path $keytool)) { throw 'keytool not found; install JDK 21 or Android Studio' }

    & $keytool -genkeypair -v `
        -storetype PKCS12 `
        -keystore $Jks `
        -alias $alias `
        -keyalg RSA -keysize 2048 -validity 10000 `
        -storepass $storePass -keypass $keyPass `
        -dname 'CN=YayLym, OU=Sumrak VPN, O=YayLym, L=Unknown, ST=Unknown, C=RU'
    Write-Host "Created $Jks"
}

$gradleProps = Join-Path $Root 'V2rayNG\gradle.properties'
$lines = @(
    ''
    '# Auto-generated by scripts/setup-play-signing.ps1 (local only, gitignored)'
    "SUMRAX_STORE_FILE=$($Jks -replace '\\','/')"
    "SUMRAX_STORE_PASSWORD=$storePass"
    "SUMRAX_KEY_ALIAS=$alias"
    "SUMRAX_KEY_PASSWORD=$keyPass"
)
Add-Content -Path $gradleProps -Value ($lines -join "`n")
Write-Host "Appended signing props to V2rayNG/gradle.properties"

@"
Sumrak VPN Play upload keystore (LOCAL — do not commit)
File: $Jks
Alias: $alias
Store password: $storePass
Key password: $keyPass
"@ | Set-Content -Path $Info -Encoding UTF8
Write-Host "Credentials saved to $Info"

if ($PushGitHubSecrets) {
    $b64Jks = [Convert]::ToBase64String([IO.File]::ReadAllBytes($Jks))
    $repo = 'Yaylymchik/Sumrak-VPN-v2ray-TM-Dealler'
    & git -C $Root credential fill 2>&1 | Out-Null
    $credProc = Start-Process -FilePath 'git' -ArgumentList @('-C', $Root, 'credential', 'fill') `
        -RedirectStandardInput "protocol=https`nhost=github.com`n" -NoNewWindow -PassThru -Wait `
        -RedirectStandardOutput (Join-Path $env:TEMP 'gh-cred-out.txt')
    $credLines = Get-Content (Join-Path $env:TEMP 'gh-cred-out.txt')
    $token = ($credLines | Where-Object { $_ -like 'password=*' }) -replace '^password=', ''
    if (-not $token) { throw 'No GitHub token from git credential' }

    function Set-GhSecret($Name, $Value) {
        $headers = @{
            Authorization = "Bearer $token"
            Accept        = 'application/vnd.github+json'
            'X-GitHub-Api-Version' = '2022-11-28'
        }
        $key = Invoke-RestMethod -Uri "https://api.github.com/repos/$repo/actions/secrets/public-key" -Headers $headers
        $bytes = [Text.Encoding]::UTF8.GetBytes($Value)
        $pub = [Convert]::FromBase64String($key.key)
        # GitHub Actions secret encryption via libsodium; use gh if available
        if (Get-Command gh -ErrorAction SilentlyContinue) {
            $env:GH_TOKEN = $token
            gh secret set $Name --body $Value --repo $repo
            return
        }
        throw 'Install GitHub CLI (gh) for -PushGitHubSecrets, or set secrets manually in repo Settings.'
    }

    Set-GhSecret 'APP_KEYSTORE_BASE64' $b64Jks
    Set-GhSecret 'APP_KEYSTORE_PASSWORD' $storePass
    Set-GhSecret 'APP_KEYSTORE_ALIAS' $alias
    Set-GhSecret 'APP_KEY_PASSWORD' $keyPass
    Write-Host 'Keystore secrets uploaded to GitHub Actions.'
    Write-Host 'Still needed: PLAY_STORE_JSON_BASE64 after Play Console API access.'
}