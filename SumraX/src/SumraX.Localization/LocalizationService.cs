using System.Globalization;
using SumraX.Core.Enums;
using SumraX.Core.Interfaces;

namespace SumraX.Localization;

public sealed class LocalizationService : ILocalizationService
{
    private static readonly Dictionary<string, Dictionary<AppLanguage, string>> Strings = BuildStrings();
    private AppLanguage _language = AppLanguage.Russian;

    public AppLanguage CurrentLanguage => _language;
    public event EventHandler? LanguageChanged;

    public string Get(string key)
    {
        if (Strings.TryGetValue(key, out var map) && map.TryGetValue(_language, out var value))
        {
            return value;
        }
        return key;
    }

    public string Format(string key, params object[] args)
    {
        var template = Get(key);
        try
        {
            return string.Format(CultureInfo.CurrentCulture, template, args);
        }
        catch
        {
            return template;
        }
    }

    public void SetLanguage(AppLanguage language)
    {
        _language = language;
        var cultureName = language switch
        {
            AppLanguage.Russian => "ru-RU",
            AppLanguage.Turkmen => "tk-TM",
            _ => "en-US"
        };
        try
        {
            var culture = CultureInfo.GetCultureInfo(cultureName);
            CultureInfo.CurrentUICulture = culture;
            CultureInfo.CurrentCulture = culture;
        }
        catch (CultureNotFoundException)
        {
            CultureInfo.CurrentUICulture = CultureInfo.GetCultureInfo("en-US");
            CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("en-US");
        }
        LanguageChanged?.Invoke(this, EventArgs.Empty);
    }

